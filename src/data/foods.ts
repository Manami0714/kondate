// 食材辞書の初期データ(開発時に新しく作ったもの)
import type { Food, FoodGroup } from '../db/types';

/** 食材を作る */
function food(
  id: string,
  name: string,
  aliases: string[],
  unit: string,
  usualAmount: number,
  foodGroup: FoodGroup,
  shelfLifeDays: number,
): Food {
  return { id, name, aliases, unit, usualAmount, kind: '食材', foodGroup, shelfLifeDays };
}

/** 調味料を作る(食品グループなし) */
function seasoning(
  id: string,
  name: string,
  aliases: string[],
  unit: string,
  usualAmount: number,
  shelfLifeDays = 365,
): Food {
  return { id, name, aliases, unit, usualAmount, kind: '調味料', foodGroup: null, shelfLifeDays };
}

