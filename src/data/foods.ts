/** 食材を作る */
function food(
  id: string,
  name: string,
  aliases: string[],
  unit: string,
  usualAmount: number,
  foodGroup: FoodGroup,
  shelfLifeDays: number,
  allergens: Allergen[] = [],
  isCondiment = false,
): Food {
  return { id, name, aliases, unit, usualAmount, kind: '食材', foodGroup, shelfLifeDays, isCondiment, allergens, allergenUncertain: false, gramsPerUnit: null };
}

