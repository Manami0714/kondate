// 初期レシピ集(動作確認用。開発時に新しく作ったもの)
// 分量は食材辞書の単位で書く。基準の人数はすべて2人分
import type { CookingMethod, Flavor } from './tags';
import type { Course, Difficulty, Recipe } from '../db/types';

interface RecipeSeed {
  id: string;
  name: string;
  minutes: number;
  difficulty: Difficulty;
  methods: CookingMethod[];
  flavors: Flavor[];
  /** [食材ID, 量] の組 */
  ingredients: [string, number][];
  steps: string[];
}

function build(course: Course, seeds: RecipeSeed[]): Recipe[] {
  return seeds.map((s) => ({
    id: `init_${s.id}`,
    name: s.name,
    course,
    ingredients: s.ingredients.map(([foodId, amount]) => ({ foodId, amount })),
    servings: 2,
    minutes: s.minutes,
    difficulty: s.difficulty,
    methods: s.methods,
    flavors: s.flavors,
    steps: s.steps,
    source: '初期',
    url: null,
    favorite: false,
  }));
}

