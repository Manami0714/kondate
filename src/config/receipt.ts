/** 日付の形の行(2026/9/25、2026年9月25日、9月25日(金) など) */
export const DATE_LINE = /\d{2,4}[/.年-]\d{1,2}[/.月-]\d{1,2}|\d{1,2}月\d{1,2}日/;

/** 電話番号の形の行(03-1234-5678、0120-000-000 など) */
export const PHONE_LINE = /\d{2,4}-\d{2,4}-\d{3,4}/;

/** ネットスーパーの「1 点 462 円☆」の行(1商品の終わり)。1つ目の数が点数 */
export const NET_SUPER_COUNT_LINE = /^(\d+)\s*点(?:\s*[\d,]+\s*円)?/;

/** 値段だけの行(「462 円☆」「¥238」「238」) */
export const PRICE_ONLY_LINE = /^[¥\\]?\s*[\d,]+\s*(円)?\s*[☆★※*外内軽]?$/;

/** レシートの数量の行(「2コX単98」「3個×@120」)。1つ目の数が個数 */
export const RECEIPT_COUNT_LINE = /^(\d+)\s*[コ個点ケヶ]\s*[x×*]\s*(?:単|@)?\s*[\d,]+/i;

/**
 * ネットスーパーの冷蔵・冷凍などの印(行の先頭)。1行で独立することも、商品名にくっつくこともある。
 * 印は商品名の始まりなので、印より前の行は写真の文字などとして扱う
 */
export const STORAGE_TAG = /^(?:冷凍|冷蔵|常温|チルド)\s*/;

/** 商品名の前につく印(冷凍・冷蔵などの区分や記号) */
export const NAME_PREFIX = /^(?:[*※#◎◇■□・]\s*)*(?:冷凍|冷蔵|常温|チルド)?\s*(?:[)】\]]\s*)?/;

/** 商品名の後ろにつく値段(「 ¥238」「 238※」「 238外」) */
export const NAME_PRICE_SUFFIX = /\s+[¥\\]?[\d,]+\s*[円☆★※*外内軽]*$/;

/** 「食材ではない」と覚えた言葉を、前後の違う商品名にも当てはめる最小の長さ(短すぎると関係ない品に当たるため) */
export const IGNORED_CONTAIN_MIN_LENGTH = 4;
